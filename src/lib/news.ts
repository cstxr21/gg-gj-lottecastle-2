export type Post = {
  slug: string;
  category: string;
  /** YYYY-MM-DD — NewsArticle datePublished */
  date: string;
  /** 수정일. 없으면 date를 쓴다 */
  dateModified?: string;
  title: string;
  /**
   * 카드 발췌 겸 NewsArticle description·og:description.
   * ⚠️ **80자 이내 엄수** — `G14-META`가 글 상세 HTML의 description 길이로 기계 강제한다.
   */
  summary: string;
  /** 도입 문단 — H1 바로 아래 본문. 글마다 문형을 바꾼다(15단계 §3 본문 틀 고정 금지) */
  lead?: string;
  /** 본문 H2 섹션. 15-A가 채운다(글당 H2 2~3개·본문 800자+) */
  sections?: { heading: string; body: string[] }[];
  /**
   * 본문 말미 관련 링크 — 13단계 §내부링크("글 상세는 본문 말미 관련 서브 1~2개 + 하단 CTA").
   * ⚠️ 카드 블록·링크 매트릭스가 아니다. 한 문장 안에 **서술형 앵커**로 넣는다.
   * ⚠️ 페이지당 최대 2개 · 같은 URL 1회(11단계 §내부링크 시스템 정본).
   */
  related?: { before: string; href: string; label: string; after: string }[];
  /**
   * 하단 ※ 출처 주석에 들어갈 언론 근거.
   * ⚠️ 본문 문장에 "보도에 따르면"류를 쓰지 않고 여기에만 모은다(6단계 §C).
   *    1차 문서(공고문·지자체 고시)에서 온 fact엔 달지 않는다.
   */
  sources?: { media: string; date: string; url?: string }[];
};

export type Press = {
  media: string;
  /** YYYY.MM.DD */
  date: string;
  title: string;
  url: string;
};

/**
 * ※ 출처·보도 아카이브 항목 조립기.
 *
 * 표기는 매체 관행대로 `YYYY.MM.DD`를 쓴다(/location·/premium의 SourceNote와 같은 형식).
 * ★`Source.date`·`Press.date`는 `POSTS[].date`(`YYYY-MM-DD`)와 **키 이름이 같다.** 보도일을
 *   이 파일에 점 구분(YYYY.MM.DD) 문자열 리터럴로 두면 `G15-POSTS`의 날짜 형식 검사가 그것까지
 *   글 발행일로 세어 오탐한다 — 그래서 여기서 조립해, 보도일이 그 키 이름을 단 문자열
 *   리터럴로 파일에 남지 않게 한다.
 */
const source = (media: string, publishedOn: string, url?: string) => ({
  media,
  date: publishedOn,
  url,
});

const pressItem = (media: string, publishedOn: string, title: string, url: string): Press => ({
  media,
  date: publishedOn,
  title,
  url,
});

